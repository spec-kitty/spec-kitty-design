#!/usr/bin/env node
/**
 * FR-009 — no CSS text in hand-authored elements source (ADR-10 §1, Confirmation #4).
 *
 * ADR-10 says CSS is authored as a real `.css` file and converted to a constructed
 * stylesheet at build time. `static styles = css`…`` is Lit's default idiom and what
 * every tutorial shows, so the regression is one autocomplete away — and nothing else
 * catches it: stylelint globs only `*.css`, and no eslint rule inspects template
 * literals.
 *
 * Scope is `.ts`, `.js` AND `.mjs`, not just `.ts`. ADR-10 Confirmation #4 says "any
 * source file", and a `.ts`-only scope is itself the evasion route.
 *
 * Generated modules are excluded by their marker line, not by a filename allowlist —
 * they contain CSS text in JS by construction, and an allowlist silently rots.
 */
import { readFileSync } from 'node:fs';
import { globSync } from 'node:fs';

// The whole package, not just src/. WP03's own T010 says "under
// packages/elements/**" and ADR-10 Confirmation #4 says "any source file" — but this
// scanned src/ only, so a hand-authored .mjs beside it
// (custom-elements-manifest.config.mjs) was never read. The stray-stylesheet glob
// below always used the wider scope; only the text scan was narrow.
const ROOT = 'packages/elements';
const GENERATED_MARKER_LINE = '// GENERATED by scripts/build-elements-css.mjs';

const FORBIDDEN = [
  // `[^.\w]` before `css`, not `\b`. The word boundary matched the prose `sk-card.css\`` —
  // a FILENAME in a doc comment — and reported it as an inlined template.
  //
  // An earlier fix stripped comments before scanning. That was WRONG and a lens measured why:
  // a regex lexer blanks comment-shaped text inside string literals too, so the ordinary glob
  // `'packages/elements/src/*.ts'` opened a phantom comment and disabled ALL FIVE checks for
  // the rest of the file. No deliberate evasion required. Narrowing the one pattern that
  // false-positived keeps every check at full strength over comments AND code.
  [/(^|[^.\w])css`/, 'Lit `css` tagged template — author CSS in @spec-kitty/styles instead'],
  [/\bunsafeCSS\s*\(/, 'unsafeCSS() — inlines CSS text into source'],
  [/new\s+CSSStyleSheet\s*\(/, 'hand-written CSSStyleSheet — use the generated module'],
  [/import\s+['"][^'"]+\.css['"]/, "bare CSS import — bundler-specific and not a constructed sheet"],
  [/\?inline['"]/, "Vite `?inline` CSS import — Vite-specific; esbuild cannot consume it"],
];

// ADR-8 constraint 1: the CSS source of record lives in @spec-kitty/styles, and
// `packages/elements` holds NONE. Checked by extension rather than by name, because
// a name-literal "exactly one sk-stub.css" test is defeated by copying the file to
// `sk-stub.styles.css` — which would also pass stylelint, and pass the token scan
const IGNORED = (f) => f.includes('/dist/') || f.includes('/node_modules/');
// below, while violating the constraint outright.
const strayCss = globSync('packages/elements/**/*.{css,scss,sass,less}', {}).filter(
  (f) => !IGNORED(f)
);
if (strayCss.length) {
  console.error('❌ CSS files exist under packages/elements (ADR-8 constraint 1, FR-009):');
  for (const f of strayCss) console.error(`   ${f}`);
  console.error(
    '   The source of record is packages/styles/src/<component>/. Elements ADOPT it via\n' +
      '   the generated module (scripts/build-elements-css.mjs); they never hold a copy.'
  );
  process.exit(1);
}

// Filtered after globbing rather than via globSync's `exclude` option: node:fs
// globSync is experimental and its exclude signature is not stable across the Node
// versions this repo runs. `dist/` is BUILD OUTPUT — bundled Lit legitimately
// contains `css` and `new CSSStyleSheet(`, so scanning it fails every run.
const files = globSync(`${ROOT}/**/*.{ts,js,mjs}`, {}).filter((f) => !IGNORED(f));
let violations = [];
for (const f of files) {
  const raw = readFileSync(f, 'utf8');
  // The marker must be on the FIRST line. `text.includes(...)` anywhere made the
  // exemption self-service: pasting the generated header into a comment in a
  // hand-authored file disabled all five checks for it — a stronger version of the
  // `sk-stub.styles.css` evasion the glob above exists to catch.
  if (raw.startsWith(GENERATED_MARKER_LINE)) continue;

  const text = raw;
  for (const [re, why] of FORBIDDEN) {
    const m = text.match(re);
    if (m) {
      const line = text.slice(0, m.index).split('\n').length;
      violations.push(`${f}:${line} — ${why}`);
    }
  }
}

// A glob that matches nothing prints a green line. node:fs globSync is still
// experimental, and a moved ROOT or a brace-expansion regression would yield
// "across 0 file(s)" and exit 0 — the same certifying-absence shape this script
// exists to prevent, in the script itself.
if (files.length === 0) {
  console.error(
    `❌ Refusing to report green over an empty file set: no .ts/.js/.mjs found under ${ROOT}.`
  );
  process.exit(1);
}

if (violations.length) {
  console.error('❌ CSS text found in hand-authored elements source (FR-009, ADR-10 §1):');
  for (const v of violations) console.error(`   ${v}`);
  process.exit(1);
}
console.log(
  `✅ No CSS in hand-authored source across ${files.length} file(s), ` +
    `and no stylesheet files under packages/elements.`
);
