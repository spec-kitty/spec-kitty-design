/**
 * DRIFT PROBES — each mutates a TEMPORARY COPY of the committed package and asserts `diffPackage`
 * names the damage. A check proven only against the pristine package has demonstrated nothing about
 * what it can see.
 */
async function checkProbes() {
  const outDir = join(ROOT, OUT_REL);
  const d = derive();
  const ref = await loadReference();
  const files = await buildPackage(d, readFileSync(join(outDir, 'DESIGN.md'), 'utf8'), ref);
  const flip = (p) => { const b = readFileSync(p); b[Math.floor(b.length / 2)] ^= 0x01; writeFileSync(p, b); };
  const onCopy = (mutate, want) => {
    const dir = mkdtempSync(join(tmpdir(), 'od-pkg-'));
    try {
      cpSync(outDir, dir, { recursive: true });
      mutate(dir);
      const problems = diffPackage(dir, files);
      return want(problems);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  };
  const names = (f) => (ps) => ps.length >= 1 && ps.some((x) => x.startsWith(f));
  const font = d.fonts[0];
  const cases = [
    ['the committed package matches a fresh build (control)', () => onCopy(() => {}, (ps) => ps.length === 0)],
    ...['components.html', `components/${d.components[0].name}.html`, 'components.manifest.json', 'manifest.json', 'metadata.json', 'tokens.css', 'DESIGN.md', `fonts/${font}`].map((f) => [
      `a ONE-BYTE change to ${f} is reported`,
      () => onCopy((dir) => flip(join(dir, f)), names(f)),
    ]),
    ['a deleted generated file is reported as missing', () => onCopy((dir) => rmSync(join(dir, 'components.html')), (ps) => ps.some((x) => /components\.html is missing/.test(x)))],
    ['a file nothing generates is reported', () => onCopy((dir) => writeFileSync(join(dir, 'stray.css'), 'x'), (ps) => ps.some((x) => /stray\.css .*nothing generates it/.test(x)))],
    ['a missing AUTHORED file is reported', () => onCopy((dir) => rmSync(join(dir, 'USAGE.md')), (ps) => ps.some((x) => /USAGE\.md \(authored\) is missing/.test(x)))],
    ['a new static form that was not regenerated is reported', async () => {
      const d2 = structuredClone(d);
      d2.components[0].forms.push({ variant: 'probe-new', file: 'x.html', markup: '<p class="sk-probe">new</p>' });
      const f2 = await buildPackage(d2, readFileSync(join(outDir, 'DESIGN.md'), 'utf8'), ref);
      const ps = diffPackage(outDir, f2);
      return ps.some((x) => x.startsWith('components.html')) && ps.some((x) => x.startsWith('components.manifest.json'));
    }],
    ['OpenDesign\'s validator (the one this build calls) rejects an unknown manifest key', () => {
      const j = JSON.parse(readFileSync(join(outDir, 'manifest.json'), 'utf8'));
      return ref.parseDesignSystemProjectManifest(JSON.stringify({ ...j, notInSchema: 1 })).ok === false;
    }],
    ['an empty generated set is refused, not certified', () => diffPackage(outDir, new Map()).length === 1],
  ];
  return cases;
}
const CHECK_PROBE_FLOOR = 15;


async function selftest() {
  let bad = 0;
  for (const [what, fn] of PROBES) {
    let ok = false;
    try {
      ok = fn() === true;
    } catch (e) {
      console.error(`  probe threw: ${what} — ${e.message}`);
    }
    console.log(`${ok ? '✅' : '❌'} ${what}`);
    if (!ok) bad++;
  }
  console.log('\n── drift probes (each mutates a temporary copy of the committed package) ──');
  const cases = await checkProbes();
  for (const [what, fn] of cases) {
    let ok = false;
    try {
      ok = (await fn()) === true;
    } catch (e) {
      console.error(`  probe threw: ${what} — ${e.message}`);
    }
    console.log(`${ok ? '✅' : '❌'} ${what}`);
    if (!ok) bad++;
  }
  if (bad) {
    console.error(`\n❌ ${bad} probe(s) did not behave as recorded.`);
    process.exit(1);
  }
  if (PROBES.length < PROBE_FLOOR || cases.length < CHECK_PROBE_FLOOR) {
    console.error(`\n❌ probe tables shrank: ${PROBES.length}/${PROBE_FLOOR} unit, ${cases.length}/${CHECK_PROBE_FLOOR} drift`);
    process.exit(1);
  }
  console.log(`\n✅ All ${PROBES.length} unit probes and ${cases.length} drift probes behaved as recorded.`);
}

export function isDirectInvocation(argv1, moduleUrl) {
  if (!argv1 || !moduleUrl) return false;
  const real = (x) => {
    try {
      return realpathSync(x);
    } catch {
      return resolve(x);
    }
  };
  return real(argv1) === real(fileURLToPath(moduleUrl));
}

if (isDirectInvocation(process.argv[1], import.meta.url)) {
  const known = new Set(['--check', '--selftest']);
  const stray = process.argv.slice(2).filter((a) => !known.has(a));
  if (stray.length) {
    console.error(`::error::unrecognised argument(s): ${stray.join(' ')}. Known: ${[...known].join(' ')}.`);
    process.exit(2);
  }
  if (process.argv.includes('--selftest')) await selftest();
  else await main({ check: process.argv.includes('--check') });
}
