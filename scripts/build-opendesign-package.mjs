#!/usr/bin/env node
/**
 * Build the OpenDesign design-system package from the library itself — REL4 (#396, epic #361).
 *
 *   node scripts/build-opendesign-package.mjs            write opendesign/spec-kitty-train/
 *   node scripts/build-opendesign-package.mjs --check    regenerate in memory, fail on any drift
 *   node scripts/build-opendesign-package.mjs --selftest run the probe table
 *
 * WHY THIS EXISTS. OpenDesign consumes a design system as a folder. The package it used before this
 * mission shipped tokens only — so a generation could match Spec Kitty's colours and type but could
 * not emit a single library component — and it was pinned to a commit that had gone 168 lines stale.
 * This builds the whole package from the library's own sources, including the components fixture,
 * so it cannot fall behind the library it describes without a red gate.
 *
 * WHAT IS GENERATED, AND WHAT IS AUTHORED.
 *   generated  tokens.css, fonts/, components.html, components/<name>.html, components.manifest.json,
 *              manifest.json, metadata.json, and the region of DESIGN.md between the GENERATED markers
 *   authored   USAGE.md, and DESIGN.md outside the markers — prose written for OpenDesign's agent,
 *              which this script preserves verbatim and never rewrites
 *
 * THREE DESIGN DECISIONS, each settled by measurement (see the mission's plan.md):
 *   1. The fixture is built from the STATIC HTML FORMS the library ships in @spec-kitty/styles. Only
 *      11 of the 159 are generated from an element's markup module (ADR-10 §3); the rest are the
 *      authored forms of styles-only components, which have no element to generate from. Both are
 *      what a consumer installs. A form that composes a custom element is left out and named — no
 *      custom element, <script> or shadow root may reach the fixture: OpenDesign emits static HTML.
 *   2. Component CSS is inlined VERBATIM. 13 components ship :host/::slotted rules, inert in light DOM.
 *      Rewriting them would teach OpenDesign against a stylesheet no consumer installs.
 *   3. components.manifest.json is produced by OPENDESIGN'S OWN extractComponentsManifest(), vendored
 *      byte-for-byte — because OpenDesign regenerates that file on import and discards anything it
 *      did not produce. A manifest computed any other way would be silently replaced.
 *
 * WHAT OPENDESIGN'S AGENT ACTUALLY SEES — measured by the WP03 consumability run, not assumed. The
 * prompt carries DESIGN.md, USAGE.md and tokens.css verbatim, but for components only a SUMMARY of
 * components.manifest.json: nine generic groups, at most eight selectors each (system.ts:1295,
 * summarizeComponentsManifestForPrompt). components.html itself is never injected when a manifest
 * exists, and at 430 KB it could not be. The agent's sandbox could not open the design-system
 * folder either. Given only component names, it emitted the right blocks with invented elements:
 * `sk-radio-choice__input` for the library's `sk-radio-choice-group__control`, 8 of 13 classes. So:
 *   - DESIGN.md's generated region carries each component's exact class vocabulary. It is pushed
 *     into every prompt, so the names are right even when no file can be read.
 *   - components/<name>.html holds one component's CSS and forms — a size an agent can read — and
 *     manifest.json declares them as preview pages, which is what puts them on OpenDesign's pull
 *     index and its `tools design-systems read` allowlist.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, rmSync, statSync, realpathSync, mkdtempSync, cpSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadReference } from './opendesign-reference.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT_REL = 'opendesign/spec-kitty-train';
const BRAND_ID = 'spec-kitty-train';
const BEGIN = '<!-- BEGIN GENERATED: components — scripts/build-opendesign-package.mjs; do not edit between these markers -->';
const END = '<!-- END GENERATED: components -->';
/** Files this script owns outright. Anything else found in the package directory is an error. */
const AUTHORED = new Set(['USAGE.md']);

/* ───────────────────────────── derivation (pure over a root) ───────────────────────────── */

const stripCssComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, '');

/** Leading HTML comments carry provenance ("GENERATED by…", "Requires tokens…"), not markup. */
const stripLeadingHtmlComments = (html) => {
  let s = html;
  for (;;) {
    const t = s.replace(/^\s+/, '');
    if (!t.startsWith('<!--')) return t.trimEnd();
    const end = t.indexOf('-->');
    if (end === -1) return t.trimEnd();
    s = t.slice(end + 3);
  }
};

/**
 * Derive everything the package is built from. PURE over `root`, so the probe table can point it at
 * a fixture tree. DERIVED, never listed: every hand-written package or component list in this
 * repository has drifted, and the one in the carried DESIGN.md had already lost `sk-theme-toggle`.
 */
export function derive(root = ROOT) {
  const problems = [];
  const S = join(root, 'packages/styles/src');
  const E = join(root, 'packages/elements/src');
  const T = join(root, 'packages/tokens/src');

  const dirsWithForms = readdirSync(S, { withFileTypes: true })
    .filter((d) => d.isDirectory() && readdirSync(join(S, d.name)).some((f) => f.endsWith('.html')))
    .map((d) => d.name)
    .sort();
  if (dirsWithForms.length === 0) {
    return { problems: ['no component under packages/styles/src has a static form — refusing to build an empty fixture'] };
  }

  const components = [];
  const omitted = [];
  const noStaticForm = [];
  for (const name of dirsWithForms) {
    const cssPath = join(S, name, `sk-${name}.css`);
    if (!existsSync(cssPath)) {
      problems.push(`${name} has static forms but no sk-${name}.css — its forms would render unstyled`);
      continue;
    }
    const css = readFileSync(cssPath, 'utf8');
    // AN @import CANNOT BE INLINED. It is only valid before every style rule; concatenated into one
    // <style> it is silently dropped — exactly how tokens.css lost JetBrains Mono for its whole life.
    if (/@import\b/.test(stripCssComments(css))) {
      problems.push(`${name}'s CSS contains @import, which a browser drops once it is inlined after other rules`);
    }
    // EVERY .html IN THE DIRECTORY IS A FORM OF THIS COMPONENT. A name filter (`sk-<dir>*.html`)
    // silently dropped seven forms: form-field/ also holds `sk-form-input-*` and `sk-form-textarea-*`,
    // which render with sk-form-field.css. Dropping them would have shipped a package telling
    // OpenDesign that form inputs cannot be emitted at all.
    const forms = readdirSync(join(S, name))
      .filter((f) => f.endsWith('.html'))
      .sort()
      .map((file) => {
        const stem = file.replace(/^sk-/, '').replace(/\.html$/, '');
        const variant = stem === name ? 'default' : stem.startsWith(`${name}-`) ? stem.slice(name.length + 1) : stem;
        return { variant, file, markup: stripLeadingHtmlComments(readFileSync(join(S, name, file), 'utf8')) };
      });
    // A FORM THAT COMPOSES A CUSTOM ELEMENT IS NOT STATIC. Two boundary-page story fixtures embed
    // <sk-entity-marker>; they render only with that element's JavaScript. They are left out of the
    // fixture — and named in DESIGN.md with the reason — rather than dropped silently or let through
    // to teach OpenDesign markup it cannot render without a runtime.
    const staticForms = [];
    for (const f of forms) {
      const why = staticOnlyProblems(`<body>${f.markup}</body>`);
      if (why.length) omitted.push({ component: name, variant: f.variant, file: f.file, why: why.join('; ') });
      else staticForms.push(f);
    }
    const shadowOnly = /:host\b|::slotted\b/.test(stripCssComments(css));
    if (staticForms.length === 0) {
      noStaticForm.push(name);
      continue;
    }
    components.push({ name, css, cssRel: `packages/styles/src/${name}/sk-${name}.css`, forms: staticForms, shadowOnly });
  }

  const elements = readdirSync(E, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(E, d.name, `sk-${d.name}.ts`)))
    .map((d) => d.name)
    .sort();
  // WHERE AN ELEMENT'S STATIC FORM LIVES. Usually its own directory; `sk-form-input` and
  // `sk-form-textarea` have theirs under form-field/. An element is only "not emittable" if no static
  // form for it exists anywhere in the fixture.
  const formHome = new Map();
  for (const c of components) {
    formHome.set(c.name, c.name);
    for (const f of c.forms) {
      const stem = f.file.replace(/^sk-/, '').replace(/\.html$/, '');
      for (const e of elements) if (stem === e || stem.startsWith(`${e}-`)) if (!formHome.has(e)) formHome.set(e, c.name);
    }
  }
  const excluded = [...new Set([...elements.filter((e) => !formHome.has(e)), ...noStaticForm])].sort();
  const coveredElsewhere = elements
    .filter((e) => formHome.has(e) && formHome.get(e) !== e)
    .map((e) => ({ element: e, component: formHome.get(e) }));

  const tokensCss = readFileSync(join(T, 'tokens.css'), 'utf8');
  const fonts = readdirSync(join(T, 'fonts')).filter((f) => statSync(join(T, 'fonts', f)).isFile()).sort();
  const version = (pkg) => JSON.parse(readFileSync(join(root, 'packages', pkg, 'package.json'), 'utf8')).version;

  return {
    problems,
    components,
    elements,
    excluded,
    coveredElsewhere,
    omitted,
    tokensCss,
    fontsDir: join(T, 'fonts'),
    fonts,
    versions: { tokens: version('tokens'), styles: version('styles'), elements: version('elements') },
  };
}

/* ───────────────────────────── assertions (pure) ───────────────────────────── */

/**
 * The static-only contract, asserted over MARKUP. A hyphenated tag is a custom element; a <script>
 * or a declarative shadow root is a runtime dependency. OpenDesign emits static HTML, so none of
 * those may appear — while inert :host rules in the inlined CSS are allowed (see decision 2 above).
 */
export function staticOnlyProblems(html) {
  const problems = [];
  const body = html.replace(/<style[\s\S]*?<\/style>/gi, '').replace(/<!--[\s\S]*?-->/g, '');
  const custom = [...new Set([...body.matchAll(/<([a-z][a-z0-9]*-[a-z0-9-]*)\b/gi)].map((m) => m[1].toLowerCase()))];
  if (custom.length) problems.push(`custom-element tags in the fixture: ${custom.join(', ')}`);
  if (/<script\b/i.test(body)) problems.push('a <script> element is in the fixture');
  if (/<template\b[^>]*\bshadowroot(mode)?\s*=/i.test(body)) problems.push('a declarative shadow root is in the fixture');
  return problems;
}

/**
 * A component's CLASS VOCABULARY: every class its own CSS selects on, plus every class its static
 * forms use. Selectors only — a declaration value such as `url(./fonts/inter.woff2)` is not a class.
 */
export function classVocabulary(css, forms) {
  const out = new Set();
  const flat = stripCssComments(css);
  for (const m of flat.matchAll(/([^{}]+)\{/g)) {
    const sel = m[1].trim();
    if (sel.startsWith('@')) continue;
    for (const c of sel.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)) out.add(c[1]);
  }
  for (const f of forms) for (const a of f.markup.matchAll(/\bclass\s*=\s*"([^"]*)"/g)) for (const t of a[1].split(/\s+/)) if (t) out.add(t);
  return [...out].sort();
}

/* ───────────────────────────── builders (pure) ───────────────────────────── */

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const indent = (s, n) => s.split('\n').map((l) => (l ? ' '.repeat(n) + l : l)).join('\n');

/** One static form, labelled by its variant — the same block in components.html and each page. */
const renderFigure = (f) =>
  `<figure data-od-variant="${esc(f.variant)}">\n  <figcaption>${esc(f.variant)}</figcaption>\n${indent(f.markup, 2)}\n</figure>`;

export function buildComponentsHtml(d) {
  const title = 'Spec Kitty — reference components';
  const description =
    `Every component of the Spec Kitty design library that has a static form — ${d.components.length} ` +
    `components, ${d.components.reduce((n, c) => n + c.forms.length, 0)} forms — generated from ` +
    `@spec-kitty/styles ${d.versions.styles}. Markup is static HTML only.`;
  const css = [
    `/* tokens: packages/tokens/src/tokens.css — @spec-kitty/tokens ${d.versions.tokens} */`,
    d.tokensCss.trimEnd(),
    ...d.components.map((c) => `\n/* component: ${c.name} — ${c.cssRel} */\n${c.css.trimEnd()}`),
  ].join('\n');
  const sections = d.components
    .map((c) => {
      const figs = c.forms
        .map(
          renderFigure,
        )
        .join('\n');
      return `<section id="${esc(c.name)}" data-od-component="${esc(c.name)}">\n  <h2>${esc(c.name)}</h2>\n${indent(figs, 2)}\n</section>`;
    })
    .join('\n');
  return [
    '<!doctype html>',
    '<html lang="en">',
    '  <head>',
    '    <meta charset="utf-8" />',
    '    <meta name="viewport" content="width=device-width, initial-scale=1" />',
    `    <title>${esc(title)}</title>`,
    `    <meta name="description" content="${esc(description)}" />`,
    '    <style>',
    css,
    '    </style>',
    '  </head>',
    '  <body>',
    `    <h1>${esc(title)}</h1>`,
    indent(sections, 4),
    '  </body>',
    '</html>',
    '',
  ].join('\n');
}

export const componentPagePath = (c) => `components/${c.name}.html`;

/**
 * One component on its own page: its CSS and every static form, at a size an agent can read. It
 * links ../tokens.css so it renders standalone for a person; an agent already has the tokens in its
 * prompt and copies only this page's <style> block and markup.
 */
export function buildComponentPage(d, c) {
  const figs = c.forms
    .map(renderFigure)
    .join('\n');
  return [
    '<!doctype html>',
    '<html lang="en">',
    '  <head>',
    '    <meta charset="utf-8" />',
    '    <meta name="viewport" content="width=device-width, initial-scale=1" />',
    `    <title>${esc(c.name)} — Spec Kitty</title>`,
    `    <meta name="description" content="${esc(`${c.name}: ${c.forms.length} static form(s) and its CSS, from @spec-kitty/styles ${d.versions.styles}. Copy the <style> block and the markup verbatim; tokens.css is required and not repeated here.`)}" />`,
    '    <link rel="stylesheet" href="../tokens.css" />',
    '    <style>',
    `/* component: ${c.name} — ${c.cssRel} */`,
    c.css.trimEnd(),
    '    </style>',
    '  </head>',
    '  <body>',
    `    <section id="${esc(c.name)}" data-od-component="${esc(c.name)}">`,
    `      <h1>${esc(c.name)}</h1>`,
    indent(figs, 6),
    '    </section>',
    '  </body>',
    '</html>',
    '',
  ].join('\n');
}

export function buildManifest(d) {
  return {
    schemaVersion: 'od-design-system-project/v1',
    id: BRAND_ID,
    name: 'Spec Kitty — train/elements-first',
    category: 'Developer tools',
    // NO COMMIT SHA. A committed file cannot know the SHA of the commit that contains it; the last
    // package recorded one and was left pinned to a stale commit. The library version is the pin.
    description:
      `Authoritative Spec Kitty and Team Kitty visual language, generated from @spec-kitty/tokens ` +
      `${d.versions.tokens}, @spec-kitty/styles ${d.versions.styles} and @spec-kitty/elements ` +
      `${d.versions.elements}, with a static components fixture covering ${d.components.length} components.`,
    source: { type: 'github', url: 'https://github.com/spec-kitty/spec-kitty-design', branch: 'train/elements-first' },
    files: { design: 'DESIGN.md', tokens: 'tokens.css', components: 'components.html' },
    componentsManifest: 'components.manifest.json',
    usage: 'USAGE.md',
    importMode: 'verbatim',
    // THE PER-COMPONENT PAGES ARE DECLARED AS PREVIEW PAGES because that is the only manifest key
    // that puts a file on OpenDesign's pull index (buildDesignSystemPullIndex) and its read
    // allowlist (buildDesignSystemPullFileAllowlist). components.html is on neither.
    preview: { dir: 'components', pages: d.components.map((c) => ({ path: componentPagePath(c), title: c.name, role: 'component' })) },
    craft: { applies: [], suggested: ['accessibility-baseline'], exemptions: [] },
  };
}

