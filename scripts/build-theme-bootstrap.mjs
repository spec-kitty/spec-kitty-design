#!/usr/bin/env node
/**
 * Build the pre-paint theme resolver from the same contract imported by sk-theme-toggle.
 *
 * Usage: node scripts/build-theme-bootstrap.mjs [--check] [--selftest]
 *
 * `--check` compares the committed classic-script artifact byte-for-byte. `--selftest`
 * exercises the check's healthy, missing, and drifted-output branches. The two flags may be
 * combined: CI keeps them as separate, readable steps while the component recipe can run both.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import * as esbuild from 'esbuild';

const SOURCE = 'packages/elements/src/theme-bootstrap.ts';
const OUTPUT = 'packages/elements/theme-bootstrap.js';
const check = process.argv.includes('--check');
const selftest = process.argv.includes('--selftest');

const unknown = process.argv.slice(2).filter((arg) => !['--check', '--selftest'].includes(arg));
if (unknown.length) {
  console.error(`usage: node scripts/build-theme-bootstrap.mjs [--check] [--selftest]`);
  process.exit(1);
}

const result = await esbuild.build({
  entryPoints: [SOURCE],
  bundle: true,
  format: 'iife',
  minify: true,
  write: false,
  metafile: true,
  legalComments: 'none',
  banner: { js: '// GENERATED by scripts/build-theme-bootstrap.mjs — DO NOT EDIT.' },
});
const next = result.outputFiles[0].text;

const inputs = Object.keys(result.metafile.inputs).sort();
const expectedInputs = [SOURCE, 'packages/elements/src/theme-toggle/theme-preference.ts'].sort();
if (JSON.stringify(inputs) !== JSON.stringify(expectedInputs)) {
  console.error(
    `❌ Bootstrap module graph drifted. Expected only the entry and authoritative contract:\n` +
    `   ${expectedInputs.join('\n   ')}\nReceived:\n   ${inputs.join('\n   ')}`,
  );
  process.exit(1);
}

const outputProblems = (current) => {
  if (current === null) return [`${OUTPUT} is missing`];
  if (current !== next) return [`${OUTPUT} is stale`];
  return [];
};

if (check) {
  const problems = outputProblems(existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : null);
  if (problems.length) {
    console.error(`❌ ${problems.join('; ')}. Run: node scripts/build-theme-bootstrap.mjs`);
    process.exit(1);
  }
  console.log(`✅ ${OUTPUT} is generated from ${SOURCE}.`);
} else if (!selftest) {
  writeFileSync(OUTPUT, next);
  console.log(`build-theme-bootstrap: ${SOURCE} -> ${OUTPUT}`);
}

if (selftest) {
  const probes = [
    ['healthy output', next, false],
    ['missing output', null, true],
    ['drifted output', `${next}\n/* planted drift */`, true],
  ];
  const failed = probes.filter(([, current, shouldFail]) =>
    (outputProblems(current).length > 0) !== shouldFail
  );
  if (failed.length) {
    console.error(`❌ Bootstrap generator selftest failed: ${failed.map(([name]) => name).join(', ')}`);
    process.exit(1);
  }
  console.log(`✅ Bootstrap generator selftest: ${probes.length}/${probes.length} probes passed.`);
}
